//! Build-time generator (`rust_binary_host` + Soong `genrule`) emitting Java constants and
//! Bionic C ABI headers straight from `yasvara_integrity_core::contract` so Java, Bionic,
//! and Rust can never drift out of sync.

use std::env;
use std::fmt::Write as _;
use std::process;

use yasvara_integrity_core::contract::*;

fn main() {
    let arg = env::args().nth(1).unwrap_or_default();
    match arg.as_str() {
        "--java" => print!("{}", emit_java()),
        "--c-header" => print!("{}", emit_c_header()),
        _ => {
            eprintln!("usage: yasvara_integrity_codegen [--java|--c-header]");
            process::exit(2);
        }
    }
}

fn emit_java_array(out: &mut String, name: &str, items: &[&str]) {
    let _ = writeln!(out, "    public static final String[] {name} = {{");
    for item in items {
        let _ = writeln!(out, "        {:?},", item);
    }
    let _ = writeln!(out, "    }};");
}

