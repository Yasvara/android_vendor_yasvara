//! Codegen tool (`pantau_layout_gen`): emits ABI-locked `pantau_abi.h` or `PantauLayout.kt`
//! directly from [`pantau::abi::LAYOUT_FIELDS`] so Rust, C++ and Kotlin can never drift.

use std::env;
use std::io::{self, Write};

use pantau::abi::{LAYOUT_FIELDS, SNAP_MAGIC, SNAP_VERSION};

fn main() -> io::Result<()> {
    let mode = env::args().nth(1).unwrap_or_else(|| "kt".to_string());
    let mut out = io::BufWriter::new(io::stdout().lock());

    match mode.as_str() {
        "h" | "cpp" => {
            writeln!(out, "// GENERATED by pantau_layout_gen — DO NOT EDIT.")?;
            writeln!(out, "#pragma once")?;
            writeln!(out, "#include <stddef.h>")?;
            writeln!(out, "#include <stdint.h>\n")?;
            writeln!(out, "#define PANTAU_SNAP_MAGIC   0x{SNAP_MAGIC:08X}u")?;
            writeln!(out, "#define PANTAU_SNAP_VERSION {SNAP_VERSION}u\n")?;
            for (name, val) in LAYOUT_FIELDS {
                writeln!(out, "#define PANTAU_{name} {val}u")?;
            }
        }
        "kt" | "kotlin" => {
            writeln!(out, "// GENERATED by pantau_layout_gen — DO NOT EDIT.")?;
            writeln!(out, "package org.yasvara.pentas.telemetry\n")?;
            writeln!(out, "object PantauLayout {{")?;
            writeln!(out, "    const val MAGIC: Int = 0x{SNAP_MAGIC:08X}")?;
            writeln!(out, "    const val VERSION: Int = {SNAP_VERSION}")?;
            for (name, val) in LAYOUT_FIELDS {
                writeln!(out, "    const val {name}: Int = {val}")?;
            }
            writeln!(out, "}}")?;
        }
        other => {
            eprintln!("Usage: pantau_layout_gen [h|kt] (got '{other}')");
            std::process::exit(2);
        }
    }
    out.flush()
}
