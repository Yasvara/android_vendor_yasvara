/// Measure pixel width of `text` at integer `scale` (`1..=12`).
#[inline]
pub fn measure_text(text: &str, scale: i32) -> i32 {
    let s = scale.max(1);
    let count = text.chars().count() as i32;
    if count == 0 {
        0
    } else {
        count * (6 * s) - s
    }
}

/// Height of text in pixels at `scale`.
#[inline]
pub const fn text_height(scale: i32) -> i32 {
    let s = if scale < 1 { 1 } else { scale };
    7 * s
}

/// Draw crisp integer-scaled text clipped safely to `surface.clip` bounds.
pub fn draw_text(surface: &mut Surface, x: i32, y: i32, text: &str, scale: i32, color: Color) {
    let s = scale.max(1);
    let clip = surface.clip;
    if clip.is_empty() || y + 7 * s <= clip.y || y >= clip.bottom() {
        return;
    }
    let mut cx = x;
    for ch in text.chars() {
        if cx >= clip.right() {
            break;
        }
        if cx + 6 * s > clip.x {
            let rows = glyph_5x7(ch);
            for (ry, &bits) in rows.iter().enumerate() {
                if bits == 0 {
                    continue;
                }
                let py0 = y + ry as i32 * s;
                if py0 + s <= clip.y || py0 >= clip.bottom() {
                    continue;
                }
                for rx in 0..5 {
                    if (bits & (1 << (4 - rx))) != 0 {
                        let px0 = cx + rx * s;
                        for dy in 0..s {
                            let py = py0 + dy;
                            if py < clip.y || py >= clip.bottom() {
                                continue;
                            }
                            for dx in 0..s {
                                surface.blend_pixel(px0 + dx, py, color, 255);
                            }
                        }
                    }
                }
            }
        }
        cx += 6 * s;
    }
}

/// Draw horizontally centered text inside `[rect.x, rect.right())`.
pub fn draw_text_centered(
    surface: &mut Surface,
    cx: i32,
    cy: i32,
    text: &str,
    scale: i32,
    color: Color,
) {
    let tw = measure_text(text, scale);
    let th = text_height(scale);
    draw_text(surface, cx - tw / 2, cy - th / 2, text, scale, color);
}
