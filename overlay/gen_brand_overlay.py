"""Writes the Yasvara brand overlay of the Lineage apps' strings.

For each listed string it takes every translation the app ships, puts Yasvara where the text
names LineageOS, and writes the result under no-rro/, a build-time overlay: the APKs are built
with these values, so no "LineageOS" string is left in them. Run it again after a Lineage
translation import (from anywhere; paths are relative to this file):

    vendor/yasvara/overlay/gen_brand_overlay.py

Strings that must keep naming LineageOS are not listed here: they are removed from the UI or
live on Legal & credits (see vendor/yasvara/tests/branding/visible_lineage.allow).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(HERE, "no-rro")
FILE = "yasvara_brand_strings.xml"

# res dir (relative to the source tree) -> names of the strings that name LineageOS.
TARGETS = {
    "packages/apps/LineageParts/res": [
        "lineageparts_title",
        "egg_title",
        "privacy_settings_category",
        "trust_feature_security_patches_explain",
    ],
    "lineage-sdk/packages/LineageSettingsProvider/res": [
        "app_name",
    ],
    "lineage-sdk/lineage/res/res": [
        "lineageos_system_label",
        "lineage_api_level",
        "lineage_updates",
        "lineage_version",
        "permlab_writeSettings",
        "permdesc_writeSettings",
        "permlab_writeSecureSettings",
        "permdesc_writeSecureSettings",
        "permdesc_useHardwareFramework",
    ],
}

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
     SPDX-FileCopyrightText: The Yasvara Project
     SPDX-License-Identifier: Apache-2.0

     Generated by vendor/yasvara/overlay/gen_brand_overlay.py from {source}.
     Do not edit; run the generator again.
-->
<resources xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2">
"""


def rebrand(text):
    return text.replace("LineageOS", "Yasvara").replace("Lineage", "Yasvara")


def strings_of(path, names):
    with open(path, encoding="utf-8") as f:
        xml = f.read()
    found = []
    for name in names:
        m = re.search(r'(<string\s+name="%s"[^>]*>)(.*?)(</string>)' % re.escape(name), xml, re.S)
        if m:
            found.append(m.group(1) + rebrand(m.group(2)) + m.group(3))
    return found


def main():
    written = 0
    for res, names in TARGETS.items():
        src = os.path.join(TOP, res)
        for values in sorted(d for d in os.listdir(src) if d.startswith("values")):
            path = os.path.join(src, values, "strings.xml")
            if not os.path.isfile(path):
                continue
            found = strings_of(path, names)
            if not found:
                continue
            out_dir = os.path.join(OUT, res, values)
            os.makedirs(out_dir, exist_ok=True)
            with open(os.path.join(out_dir, FILE), "w", encoding="utf-8") as f:
                f.write(HEADER.format(source=os.path.join(res, values, "strings.xml")))
                for s in found:
                    f.write("    " + s + "\n")
                f.write("</resources>\n")
            written += 1
    print(f"wrote {written} overlay files under {os.path.relpath(OUT, TOP)}")


if __name__ == "__main__":
    main()
